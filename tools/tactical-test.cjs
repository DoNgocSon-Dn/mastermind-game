const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ctx = vm.createContext({ console });
for (const file of ['js/config.js', 'js/systems/wave.js', 'js/ui/tactical.js']) vm.runInContext(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'), ctx);
vm.runInContext(`
  globalThis.manager = new WaveManager([[{type:'tank', count:2, path:1}, {type:'tank', count:3, path:1, tunnelIndex:0}, {type:'boss', count:1, path:0}]], () => {}, () => {}, () => {});
  globalThis.info = TacticalInfo;
`, ctx);
const wm = ctx.manager;
const summary = ctx.info.summarizeWave(wm.previewNextWave());
assert.equal(summary.total, 6);
assert.equal(summary.routes[0].path, 0);
assert.equal(summary.routes[0].enemies[0].boss, true);
assert.equal(summary.routes[1].enemies[0].count, 5);
assert.equal(summary.routes[1].tunnel, true);
wm.previewNextWave().groups[0].count = 999;
assert.equal(wm.waveDefs[0][0].count, 2, 'Preview cannot mutate actual waves');
wm.update(10);
assert.equal(wm.waveIndex, -1, 'First wave waits for player preparation');
wm.requestNextWaveNow();
assert.equal(wm.active, true);
assert.equal(wm.previewNextWave(), null);
wm.finishedAllSpawns = true;
assert.equal(wm.previewNextWave(), null);
vm.runInContext('globalThis.endless = new WaveManager([], () => {}, null, null, n => [{type:"normal",count:n+5}]);', ctx);
assert.equal(ctx.endless.previewNextWave().groups[0].count, 5);
assert.equal(ctx.endless.waveDefs.length, 0, 'Endless preview cannot enqueue waves');
ctx.endless.setAutoAdvance(true);
ctx.endless.update(3);
assert.equal(ctx.endless.active, true, 'Auto mode can start the first wave');
const rows = ctx.info.statRows('archer', { damage: 20, rate: .5, range: 100 }, { damageMult: 1.12, rangeMult: .7, rateMult: 2 });
assert.equal(rows[0][1], '22.4');
assert.equal(rows[1][1], '1');
assert.equal(rows[2][1], '70px');
const tesla = vm.runInContext('TacticalInfo.statRows("artillery", CONFIG.towers.artillery.branches.B)', ctx);
assert.equal(tesla[3][1], 'Phép', 'Tesla lightning deals magic damage');
const barracks = ctx.info.statRows('barracks', { dmg:4, atkRate:1, hp:90, armor:.2, respawn:13 });
assert.equal(barracks[0][1], '4');
assert.equal(barracks[3][1], '20%');
assert.equal(barracks[4][1], 3);
console.log('PASS: wave totals, routes, tunnels, bosses, immutable previews, manual/auto first wave, endless, effective tower stats');
